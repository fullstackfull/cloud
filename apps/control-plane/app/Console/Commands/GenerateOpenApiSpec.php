    }

    /**
     * @param  array<string, mixed>  $operation
     * @return array<string, mixed>
     */
    private static function operation(string $name, RoutingRoute $route, array $operation): array
    {
        $out = [
            'operationId' => str_replace('.', '_', $name),
            'tags' => [(string) ($operation['tag'] ?? 'Other')],
            'summary' => (string) ($operation['summary'] ?? ''),
        ];

        if (isset($operation['description'])) {
            $out['description'] = (string) $operation['description'];
        }

        if (($permission = $operation['permission'] ?? null) !== null) {
            $out['description'] = trim(($out['description'] ?? '')."\n\nRequires the `".$permission.'` permission.');
        }

        $parameters = self::parameters($route, $operation);

        if ($parameters !== []) {
            $out['parameters'] = $parameters;
        }

        if (isset($operation['body'])) {
            $out['requestBody'] = self::requestBody($operation);
        }

        $out['security'] = ($operation['auth'] ?? true) === false
            ? []
            : [['sessionCookie' => []], ['personalAccessToken' => []]];

        $out['responses'] = self::responses($operation);

        return $out;
    }

    /**
     * @param  array<string, mixed>  $operation
     * @return list<array<string, mixed>>
     */
    private static function parameters(RoutingRoute $route, array $operation): array
    {
        $parameters = [];

        foreach ($route->parameterNames() as $parameter) {
            $parameters[] = [
                'name' => $parameter,
                'in' => 'path',
                'required' => true,
                'schema' => ['type' => 'string'],
            ];
        }

        $envelope = is_array($operation['response'] ?? null) ? ($operation['response']['envelope'] ?? null) : null;

        if ($envelope === 'page') {
            $parameters[] = ['$ref' => '#/components/parameters/page'];
            $parameters[] = ['$ref' => '#/components/parameters/perPage'];
        }

        /** @var list<string> $query */
        $query = $operation['query'] ?? [];

        foreach ($query as $field) {
            $parameters[] = [
                'name' => $field,
                'in' => 'query',
                'required' => false,
                'schema' => ['type' => 'string'],
            ];
        }

        if (($operation['auth'] ?? true) !== false) {
            $parameters[] = ['$ref' => '#/components/parameters/customerId'];
        }

        $method = in_array('POST', $route->methods(), true) || in_array('PUT', $route->methods(), true);

        if ($method && ($operation['auth'] ?? true) !== false) {
            $parameters[] = ['$ref' => '#/components/parameters/idempotencyKey'];
        }

        return $parameters;
    }

    /**
     * @param  array<string, mixed>  $operation
     * @return array<string, mixed>
     */
    private static function requestBody(array $operation): array
    {
        /** @var list<string> $fields */
        $fields = $operation['body'];

        $properties = [];

        foreach ($fields as $field) {
            $properties[$field] = ['description' => 'See the endpoint description; validated server-side.'];
        }

        return [
            'required' => true,
            'content' => [
                'application/json' => [
                    'schema' => [
                        'type' => 'object',
                        'properties' => $properties,
                    ],
                ],
            ],
        ];
    }

    /**
     * @param  array<string, mixed>  $operation
     * @return array<int|string, mixed>
     */
    private static function responses(array $operation): array
    {
        /** @var array<string, mixed> $response */
        $response = $operation['response'] ?? ['envelope' => 'none', 'status' => 204];

        $status = (string) ($response['status'] ?? 200);
        $envelope = (string) ($response['envelope'] ?? 'none');
        $schema = isset($response['schema']) ? (string) $response['schema'] : null;

        $success = match ($envelope) {
            'page' => ['description' => 'A page of results.', 'content' => self::json($schema.'Page')],
            'single' => ['description' => 'The resource.', 'content' => self::json($schema.'Response')],
            'list' => ['description' => 'Every result, unpaged.', 'content' => [
                'application/json' => ['schema' => [
                    'type' => 'object',
                    'required' => ['data'],
                    'properties' => ['data' => [
                        'type' => 'array',
                        'items' => ['$ref' => '#/components/schemas/'.$schema],
                    ]],
                ]],
            ]],
            'redirect' => ['description' => 'A redirect back to the portal.'],
            default => ['description' => 'No content.'],
        };

        // Both headers are on every response the application sends: the
        // correlation id from global middleware, the remaining allowance from
        // the throttler. Documenting them is what lets a client log the first
        // and back off on the second.
        $success['headers'] = [
            'X-Request-Id' => ['$ref' => '#/components/headers/RequestId'],
            'X-RateLimit-Remaining' => ['$ref' => '#/components/headers/RateLimitRemaining'],
        ];

        $responses = [$status => $success];

        if (($operation['auth'] ?? true) !== false) {
            $responses['401'] = self::errorResponse('Not authenticated. `auth.unauthenticated`.');
            $responses['403'] = self::errorResponse('Not permitted. `auth.forbidden`, whatever the underlying refusal was.');
        }

        if (isset($operation['body'])) {
            $responses['422'] = self::errorResponse('The body did not validate. `validation.failed`, with the failing fields in `error.details`.');
        }

        $responses['404'] = self::errorResponse(
            'Not found. An identifier belonging to another account answers this rather than 403: a 403 confirms the id exists, which over a loop is an inventory of the platform.',
        );

        $responses['429'] = [
            'description' => 'Rate limited. `Retry-After` says how long to wait.',
            'headers' => ['Retry-After' => ['$ref' => '#/components/headers/RetryAfter']],
            'content' => self::json('Error'),
        ];

        return $responses;
    }

    /**
     * @return array<string, mixed>
     */
    private static function errorResponse(string $description): array
    {
        return ['description' => $description, 'content' => self::json('Error')];
    }

    /**
     * @return array<string, mixed>
     */
    private static function json(string $schema): array
    {
        return ['application/json' => ['schema' => ['$ref' => '#/components/schemas/'.$schema]]];
    }
}
