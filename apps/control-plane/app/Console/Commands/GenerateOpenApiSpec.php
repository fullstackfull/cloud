<?php

declare(strict_types=1);

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Routing\Route as RoutingRoute;
use Illuminate\Support\Facades\Route;
use Lynomia\Support\YamlEmitter;
use RuntimeException;

/**
 * Writes docs/openapi.yaml from the routes the application actually registers.
 *
 * The structure — which paths exist, which methods, which path parameters,
 * whether a route is authenticated, which permission an operator route needs —
 * is read from the route table rather than typed, because a hand-maintained
 * list of endpoints diverges from the application the first week nobody
 * remembers to update it.
 *
 * The meaning — what an endpoint is for, what its body looks like, why a 409
 * means what it means — is hand-written in resources/openapi/operations.php,
 * because none of it is derivable from a route table.
 *
 * The command refuses to write a document while any registered route has no
 * entry, and while any entry names a route that does not exist. That is the
 * gate: an endpoint cannot be added without being documented, and the document
 * cannot describe an endpoint the platform does not serve.
 */
final class GenerateOpenApiSpec extends Command
{
    protected $signature = 'openapi:generate {--check : Fail if the committed file is out of date, and write nothing}';

    protected $description = 'Generate the OpenAPI 3.1 description of this API from the route table';

    private const string OUTPUT = 'docs/openapi.yaml';

    public function handle(): int
    {
        $operations = require base_path('resources/openapi/operations.php');
        $components = require base_path('resources/openapi/components.php');
        $schemas = require base_path('resources/openapi/schemas.php');

        $routes = self::describableRoutes();

        if (($problem = self::disagreement($routes, $operations)) !== null) {
            $this->error($problem);

            return self::FAILURE;
        }

        $document = self::document($routes, $operations, $components, $schemas);
        $yaml = "# Generated by `php artisan openapi:generate`. Do not edit by hand.\n"
            ."# The meaning lives in resources/openapi/; this file is its serialisation.\n"
            .YamlEmitter::emit($document);

        $path = base_path('../../'.self::OUTPUT);

        if ($this->option('check')) {
            $current = is_file($path) ? file_get_contents($path) : '';

            if ($current !== $yaml) {
                $this->error(self::OUTPUT.' is out of date. Run `php artisan openapi:generate`.');

                return self::FAILURE;
            }

            $this->info(self::OUTPUT.' is up to date: '.count($routes).' operations.');

            return self::SUCCESS;
        }

        file_put_contents($path, $yaml);
        $this->info('Wrote '.self::OUTPUT.': '.count($routes).' operations.');

        return self::SUCCESS;
    }

    /**
     * Every route this document is expected to describe.
     *
     * The API and the webhook endpoint. Nothing else is registered — there are
     * no HTML routes on this application — but the filter is explicit so that
     * adding one does not silently enlarge the document.
     *
     * @return array<string, RoutingRoute> keyed by route name
     */
    public static function describableRoutes(): array
    {
        $routes = [];

        /*
         * getRoutes() is typed as the collection interface, which is not
         * declared iterable even though the implementation is. Taking the
         * array is both honest about that and stable.
         */
        foreach (Route::getRoutes()->getRoutes() as $route) {
            $uri = $route->uri();

            if (! str_starts_with($uri, 'api/') && ! str_starts_with($uri, 'webhooks/')) {
                continue;
            }

            $name = $route->getName();

            if ($name === null) {
                throw new RuntimeException(sprintf(
                    'The route %s has no name, so it cannot be documented. Name it.',
                    $uri,
                ));
            }

            $routes[$name] = $route;
        }

        ksort($routes);

        return $routes;
    }

    /**
     * @param  array<string, RoutingRoute>  $routes
     * @param  array<string, mixed>  $operations
     */
    private static function disagreement(array $routes, array $operations): ?string
    {
        $undocumented = array_diff(array_keys($routes), array_keys($operations));

        if ($undocumented !== []) {
            return sprintf(
                "These routes are registered and not documented in resources/openapi/operations.php:\n  %s",
                implode("\n  ", $undocumented),
            );
        }

        $imaginary = array_diff(array_keys($operations), array_keys($routes));

        if ($imaginary !== []) {
            return sprintf(
                "These operations describe routes the application does not register:\n  %s",
                implode("\n  ", $imaginary),
            );
        }

        return null;
    }

    /**
     * @param  array<string, RoutingRoute>  $routes
     * @param  array<string, mixed>  $operations
     * @param  array<string, mixed>  $components
     * @param  array<string, mixed>  $schemas
     * @return array<string, mixed>
     */
    private static function document(array $routes, array $operations, array $components, array $schemas): array
    {
        $paths = [];

        foreach ($routes as $name => $route) {
            /** @var array<string, mixed> $operation */
            $operation = $operations[$name];

            $path = '/'.$route->uri();

            foreach ($route->methods() as $method) {
                if (in_array($method, ['HEAD', 'OPTIONS'], true)) {
                    continue;
                }

                $paths[$path][strtolower($method)] = self::operation($name, $route, $operation);
            }
        }

        ksort($paths);

        /** @var callable(string): array<string, mixed> $page */
        $page = $components['page'];
        /** @var callable(string): array<string, mixed> $single */
        $single = $components['single'];

        $allSchemas = $components['schemas'];

        /*
         * Only the envelope variants something references. Emitting a Page and
         * a Response for every resource whether or not either is used fills the
         * document with components nobody can reach — which a validator
         * reports, correctly, as dead weight in a public contract.
         */
        $referenced = self::referencedSchemas($paths);

        foreach ($schemas as $schemaName => $schema) {
            $allSchemas[$schemaName] = $schema;

            if (isset($referenced[$schemaName.'Page'])) {
                $allSchemas[$schemaName.'Page'] = $page($schemaName);
            }

            if (isset($referenced[$schemaName.'Response'])) {
                $allSchemas[$schemaName.'Response'] = $single($schemaName);
            }
        }

        ksort($allSchemas);

        return [
            'openapi' => '3.1.0',
            'info' => self::apiInfo(),
            'servers' => [
                ['url' => '{origin}', 'description' => 'The deployment you are talking to.', 'variables' => [
                    'origin' => ['default' => 'https://cloud.lynomia.test', 'description' => 'Scheme and host of the control plane.'],
                ]],
            ],
            'tags' => self::tags($operations),
            'security' => [
                ['sessionCookie' => []],
                ['personalAccessToken' => []],
            ],
            'paths' => $paths,
            'components' => [
                'securitySchemes' => $components['securitySchemes'],
                'parameters' => $components['parameters'],
                'headers' => $components['headers'],
                'schemas' => $allSchemas,
            ],
        ];
    }

    /**
     * Every `#/components/schemas/X` the paths object mentions.
     *
     * @param  array<string, mixed>  $paths
     * @return array<string, true>
     */
    private static function referencedSchemas(array $paths): array
    {
        // UNESCAPED_SLASHES matters: json_encode writes "#\/components\/..."
        // by default, and a pattern looking for the unescaped form silently
        // matches nothing — which prunes every envelope the document uses.
        $json = json_encode($paths, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);

        preg_match_all('#\#/components/schemas/([A-Za-z0-9_]+)#', $json, $matches);

        return array_fill_keys($matches[1], true);
    }

    /**
     * @return array<string, mixed>
     */
    private static function apiInfo(): array
    {
        return [
            'title' => 'Lynomia Cloud API',
            'version' => '1.0.0',
            'summary' => 'Cloud VPS, dedicated servers and shared hosting, with their billing.',
            'description' => <<<'TEXT'
