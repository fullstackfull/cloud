    /**
     * @param  array<string, mixed>  $operations
     * @return list<array<string, string>>
     */
    private static function tags(array $operations): array
    {
        $tags = [];

        foreach ($operations as $operation) {
            $tag = is_array($operation) ? (string) ($operation['tag'] ?? 'Other') : 'Other';
            $tags[$tag] = true;
        }

        $names = array_keys($tags);
        sort($names);

        // Every tag says what it is for. A generated document with fourteen
        // bare tag names is a navigation menu with no labels.
        $descriptions = [
            'Account' => 'The signed-in person: their profile, their password, their second factor and the devices they are signed in on.',
            'API tokens' => 'Credentials for integrations. Shown once at creation; the platform stores a hash.',
            'Authentication' => 'Signing in and out, verifying an address, resetting a password. Rate-limited harder than anything else here.',
            'Backups' => 'Backups of a machine. A state moves to succeeded only when the provider says the task finished, never because a job was accepted.',
            'Billing' => 'Invoices, subscriptions, payments and the wallet. Money is integer minor units throughout.',
            'Catalogue' => 'What is for sale, priced in the account\'s currency.',
            'Cloud VPS' => 'Virtual machines: their state, their power, their console and their reinstalls.',
            'Dedicated servers' => 'Physical machines, controlled through a BMC the API never exposes.',
            'IP addresses' => 'Addresses assigned to the account, and their reverse DNS.',
            'Notifications' => 'What the platform has told this customer, and what they have read. Security and billing messages cannot be switched off.',
            'Operator' => 'The NOC surface. Same guard as the customer API — what separates them is that every route here names the permission it needs.',
            'Orders' => 'Placing and cancelling orders. Nothing is provisioned until a payment has been verified server-side.',
            'Services' => 'What the account owns, whatever kind it is, and what the platform has done to it.',
            'Support' => 'Tickets between an account and the support team. A customer may open, reply and close; resolving is the team\'s judgement and is not on this surface. Internal notes never appear here at all.',
            'Shared hosting' => 'Panel accounts, their usage, and single-use sign-in links to the panel.',
            'Team' => 'Who belongs to this account and what each of them may do. The three /invitations routes are the invitee\'s side, and are the only customer routes that work for somebody who belongs to no account yet.',
